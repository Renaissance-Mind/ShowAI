import {readFile,writeFile,mkdir,mkdtemp,rm} from 'node:fs/promises';
import {join,resolve,dirname,relative} from 'node:path';
import {fileURLToPath} from 'node:url';
import {tmpdir} from 'node:os';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..'),source=join(root,'src/surface/ink-kernel');
const clang=process.env.SHOWAI_INK_CLANG||'clang++',linker=process.env.SHOWAI_INK_WASM_LD||'wasm-ld';
const entries=['coverage-kernel.cpp','analytic-path.cpp','boundary/wasm-runtime.cpp'];
const api=['sa_coverage_state_bytes','sa_coverage_initialize','sa_coverage_prepare','sa_coverage_summary','sa_coverage_copy_vertices','sa_coverage_copy_draws','sa_coverage_diagnostics','sa_coverage_supports','sa_coverage_destroy'];
const flags=['--target=wasm32-unknown-unknown','-mbulk-memory','-std=c++17','-O2','-ffp-contract=off','-fno-fast-math','-fno-exceptions','-fno-rtti','-fno-builtin','-nostdlib'];
const linkFlags=['--no-entry','--stack-first','-z','stack-size=2097152','--initial-memory=4194304','--max-memory=268435456','--strip-all','--export-memory','--export=__heap_base',...api.map(name=>'--export='+name)];
const hash=value=>createHash('sha256').update(value).digest('hex'),files=new Map();
async function capture(name){
  if(files.has(name))return;const bytes=await readFile(join(source,name));files.set(name,bytes);
  for(const match of bytes.toString('utf8').matchAll(/^\s*#include\s*"([^"]+)"/gm)){
    const dependency=relative(source,resolve(source,dirname(name),match[1]));
    if(dependency.startsWith('..')||!dependency)throw Error('Coverage dependency escapes kernel: '+dependency);
    await capture(dependency);
  }
}
for(const name of entries)await capture(name);
if([...files.keys()].some(name=>/test|fixture|mock/.test(name)))throw Error('Test code entered coverage source closure');
const temp=await mkdtemp(join(tmpdir(),'showai-coverage-wasm-'));
try{
  const objects=[];
  for(const [index,name] of entries.entries()){
    const object=join(temp,index+'.o');execFileSync(clang,[...flags,'-c',join(source,name),'-o',object],{stdio:'inherit'});objects.push(object);
  }
  const wasm=join(temp,'coverage.wasm');execFileSync(linker,[...linkFlags,...objects,'-o',wasm],{stdio:'inherit'});
  const bytes=await readFile(wasm),module=new WebAssembly.Module(bytes),imports=WebAssembly.Module.imports(module),exports=WebAssembly.Module.exports(module).map(value=>value.name).sort();
  if(imports.length||JSON.stringify(exports)!==JSON.stringify([...api,'memory','__heap_base'].sort()))throw Error('Unexpected coverage imports/exports');
  const provenance={abiVersion:1,derivedOnly:true,ephemeralWorkspace:true,sourceHashes:Object.fromEntries([...files.keys()].sort().map(name=>[name,hash(files.get(name))])),wasmSha256:hash(bytes),bytes:bytes.length,compiler:execFileSync(clang,['--version'],{encoding:'utf8'}).split('\n')[0],flags,linkFlags,imports,exports};
  const text=`// Generated by scripts/build-coverage-kernel.mjs. Editable source is never this mesh.\nexport const coverageKernelProvenance=${JSON.stringify(provenance)};\nObject.freeze(coverageKernelProvenance.sourceHashes);Object.freeze(coverageKernelProvenance);\nexport const coverageKernelWasmBase64=${JSON.stringify(bytes.toString('base64'))};\n`;
  const target=join(source,'coverage-kernel-wasm.mjs');
  if(process.argv.includes('--check')){if(await readFile(target,'utf8')!==text)throw Error('Coverage module is stale');}
  else await writeFile(target,text);
  if(process.env.SHOWAI_COVERAGE_TEST_OUTPUT){const output=process.env.SHOWAI_COVERAGE_TEST_OUTPUT;await mkdir(output,{recursive:true});await writeFile(join(output,'coverage-public.wasm'),bytes);await writeFile(join(output,'coverage-public-manifest.json'),JSON.stringify(provenance,null,2)+'\n');}
  console.log(JSON.stringify({...provenance,sourceHashes:Object.keys(provenance.sourceHashes)}));
}finally{await rm(temp,{recursive:true,force:true});}
