import { readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

// Only generates imports. The existing plugin remains the canonical source;
// bundlers embed the same files without a second editable copy of the content.
export async function mcpSkillSourceModule(sourceRoot = root) {
  const directory = join(sourceRoot, "plugins/showai/skills");
  const files = [];
  async function visit(path = "") {
    for (const entry of (
      await readdir(join(directory, path), { withFileTypes: true })
    ).sort((a, b) => a.name.localeCompare(b.name))) {
      const name = path ? `${path}/${entry.name}` : entry.name;
      if (entry.isDirectory()) await visit(name);
      else if (entry.isFile() && /\.(md|py)$/.test(name)) files.push(name);
      else throw new Error(`Unsupported skill source: ${name}`);
    }
  }
  await visit();
  const names = files
    .filter((path) => path.endsWith("/SKILL.md"))
    .map((path) => path.split("/")[0]);
  if (!names.length) throw new Error("No ShowAI skills found.");
  for (const name of names) {
    const markdown = await readFile(join(directory, name, "SKILL.md"), "utf8");
    if (
      !markdown.startsWith(`---\nname: ${name}\n`) ||
      !/^description: .+$/m.test(markdown)
    )
      throw new Error(`Invalid skill frontmatter: ${name}`);
  }
  return `// Generated by scripts/mcp-skill-source.mjs; edit plugins/showai/skills instead.\n${files.map((path, index) => `import source${index} from ${JSON.stringify(`../../plugins/showai/skills/${path}?raw`)};`).join("\n")}\n\nexport const mcpSkillNames = ${JSON.stringify(names)} as const;\nexport const mcpSkillSources: Record<string, string> = {\n${files.map((path, index) => `  ${JSON.stringify(path)}: source${index},`).join("\n")}\n};\n`;
}

export async function generateMcpSkillSource(sourceRoot = root) {
  const destination = join(
    sourceRoot,
    "src/agent/mcp-skill-source.generated.ts",
  );
  const output = await mcpSkillSourceModule(sourceRoot);
  const current = await readFile(destination, "utf8").catch((error) => {
    if (error.code === "ENOENT") return undefined;
    throw error;
  });
  if (current !== output) await writeFile(destination, output);
  return destination;
}

if (
  process.argv[1] &&
  relative(root, resolve(process.argv[1])) === "scripts/mcp-skill-source.mjs"
)
  console.log(await generateMcpSkillSource());
