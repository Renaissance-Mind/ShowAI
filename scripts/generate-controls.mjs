import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { transform } from "esbuild";
import { compile } from "tailwindcss";
import daisyui from "daisyui";

const source = new URL("../src/design/controls.source.css", import.meta.url);
const output = new URL("controls.css", source);
const compiler = await compile(await readFile(source, "utf8"), {
  async loadModule(id, base) {
    if (id !== "daisyui") throw new Error("Unexpected controls plugin: " + id);
    return {
      module: daisyui,
      base,
      path: fileURLToPath(import.meta.resolve(id)),
    };
  },
});
// ShowAI already exposes --border as a color to component authors.
const styles = compiler
  .build([])
  .replaceAll("var(--border)", "var(--control-border-width)");
const { code } = await transform(styles, {
  loader: "css",
  minify: true,
  target: ["chrome120", "safari17"],
  legalComments: "none",
});
const notices = await Promise.all(
  ["daisyui", "tailwindcss"].map((name) =>
    readFile(
      new URL("../node_modules/" + name + "/LICENSE", import.meta.url),
      "utf8",
    ),
  ),
);
const css =
  "/*! Generated by npm run controls:generate.\n" +
  notices.map((s) => s.trim()).join("\n\n") +
  "\n*/\n" +
  code;
if (process.argv.includes("--check")) {
  if ((await readFile(output, "utf8")) !== css) {
    throw new Error(
      "Control styles are out of date. Run npm run controls:generate.",
    );
  }
} else {
  await writeFile(output, css);
}
